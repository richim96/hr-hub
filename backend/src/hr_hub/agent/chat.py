"""Chat agent submodule."""

import json
import re
from dataclasses import dataclass, field

from pydantic_ai import Agent, RunContext
from sqlalchemy import text
from sqlalchemy.orm import Session

from hr_hub.agent import LOGGER


# ---------------------------------------------------------------------------
# SQL safety — only SELECT statements are allowed
# ---------------------------------------------------------------------------
_DANGEROUS_SQL: re.Pattern[str] = re.compile(
    r"\b(INSERT|UPDATE|DELETE|DROP|CREATE|ALTER|TRUNCATE|EXEC|EXECUTE|PRAGMA|ATTACH|DETACH)\b",
    re.IGNORECASE,
)
_RESULT_LIMIT: int = 50

# ---------------------------------------------------------------------------
# DB schema injected into the system prompt so the LLM can write correct SQL
# ---------------------------------------------------------------------------
