"""Model for the HR Hub agent output."""

from datetime import datetime
from typing import Literal, TypeAlias, Optional

from pydantic import BaseModel


class ResponseDTO(BaseModel):
    """Model for the HR Hub output.

    Attributes:
        event_id (str): Unique identifier for the processed event (e.g., "evt_002")
        event_type (str): Type of the event processed (e.g., "employee_change")
        status (str): Processing status (e.g., "completed", "pending", "failed")
        processed_at (datetime): Timestamp when the event was processed
        llm_result (LLMResult, optional): Result from the LLM analysis, if applicable
        actions_taken (list[Action]): List of actions taken by the agent based on the event
        summary (str): A brief summary of the agent's processing and decisions
    """

    event_id: str
    event_type: EventType
    status: Status
    processed_at: datetime
    llm_result: Optional[LLMResult] = None
    actions_taken: list[Action]
    summary: str


class LLMResult(BaseModel):
    """Result from the LLM analysis of the event.

    Attributes:
        topics (list[str]): Key topics identified in the event description
        confidence (float): Confidence score of the LLM's analysis (0.0 to 1.0)
        extracted_info (dict): Structured information extracted from the event description
        draft_response (str): A draft response generated by the LLM for the event
    """

    topics: list[str]
    confidence: float
    extracted_info: dict
    draft_response: str


class Action(BaseModel):
    """Action taken based on the request.

    Attributes:
        action (str): Description of the action taken (e.g., "Updated employee record", "Created IT ticket")
        success (bool): Whether the action was successful
        details (str): Additional details about the action taken, such as error messages if it failed
    """

    action: ActionType
    success: bool
    details: str


# ----- Type Aliases -----
EventType: TypeAlias = Literal["new_hire", "employee_change", "ticket"]
Status: TypeAlias = Literal["completed", "pending", "failed"]
ActionType: TypeAlias = Literal[
    "create_employee",
    "update_employee",
    "create_task",
    "create_ticket",
    "update_ticket",
    "close_ticket",
]
